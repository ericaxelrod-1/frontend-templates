import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { Client } from 'pg';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { databaseConfig } from '../support/database.js';
import { REPOSITORY_ROOT, relativeToRepository } from '../support/paths.js';

/**
 * The committed OpenAPI contract is not stale. A gating step of `npm run verify`,
 * inside the smoke suite (`vitest.config.smoke.ts` includes `*.smoke-spec.ts`).
 *
 * ## Why this exists
 *
 * `openapi.json` was once a 610-byte placeholder with **no paths**, committed and
 * unchanged across **thirteen** migrations, and nothing failed — because no test
 * compared it to anything. The Angular types are generated from that file, so the
 * committed contract was empty while the database was fully modelled. It has since
 * been regenerated by hand four times in this workstream, each time silently: the
 * failure mode is invisible from the diff, because a spec that is stale and a spec
 * that is current are both "a JSON file nobody edited".
 *
 * ## What is compared, and why it is not the SERVED document
 *
 * The obvious gate is *"fetch `GET /` from PostgREST and diff it against the
 * committed file"*. **It was measured against PostgREST 16.4 and rejected**, for
 * three reasons, all of them permanent rather than incidental:
 *
 *  1. **The served document is Swagger 2.0**, so the comparison needs a conversion
 *     step (`swagger2openapi`, not installed here) before anything can be compared
 *     at all. `definitions` → `components.schemas`, `in: body` parameters →
 *     `components.requestBodies` — a transformation this repository does not own.
 *  2. **`servers[0].url` is not a property of the schema.** Measured from a live
 *     server: PostgREST reports `host: "127.0.0.1:3001"`, `basePath: "/"`,
 *     `schemes: ["http"]`, which the converter renders as
 *     `servers: [{"url": "http://127.0.0.1:3001"}]`. It is derived from the
 *     **bound** `server-host` / `server-port`, so it changes with the machine, and
 *     a byte comparison goes red for a reason that is not staleness.
 *  3. **`info.version` is the tool's version** — measured `"16.4"`, alongside
 *     `info.title` `"standard public schema"`, PostgREST's defaults. A PostgREST
 *     upgrade changes both with no schema change at all.
 *
 * So the gate compares the committed file against **the live catalog** — the thing
 * the served document is derived from in the first place. That answers the question
 * that matters (does the committed contract still describe this database?) with no
 * conversion, no PostgREST process, no free port, and **nothing to normalise**: there
 * is not one environment-specific field in the comparison, which is the only way to
 * be sure the list never needs a hand-tuned entry to go green.
 *
 * It is also **not weaker** than the served-document diff for the failure it exists
 * to catch. Because the comparison is against the catalog, it survives the
 * conversion losing something — the committed file is post-conversion, so a table or
 * column dropped by `swagger2openapi` is a difference from the catalog and goes red
 * here too.
 *
 * ## What it does NOT catch, stated rather than left to be discovered
 *
 * A column's **type, format or nullability**; a column or table **description**; a
 * missing HTTP verb on a path; a malformed `$ref`; an `/rpc/` function that no longer
 * exists; and `frontend/src/app/api/schema.ts` being stale relative to
 * `openapi.json`. Type comparison in particular was considered and refused: it needs
 * a hand-written Postgres → Swagger type map for every column in the schema, and one
 * wrong entry makes the gate red on a correct tree — which is how a gate gets
 * disabled. Column *names* and *existence* have no such map, so they are what is
 * asserted here.
 *
 * ## The database
 *
 * The live one named by `DB_*`, which `.env.test` points at. No throwaway database,
 * no PostgREST process: a contract gate that needs a server is a contract gate
 * nobody runs.
 */

const TIMEOUT = 60_000;

const SPEC_PATH = join(REPOSITORY_ROOT, 'openapi.json');
const CONFIG_PATH = join(REPOSITORY_ROOT, 'postgrest.conf');

/**
 * The shape of the committed document, narrowed by HAND from `unknown`.
 *
 * `JSON.parse` returns `any`; §2.6 bans `any` and this is the place it would have
 * been used. The narrowing is a validation rather than a cast: a field that is not
 * the shape it claims throws, so a hand-edited spec that moved `components.schemas`
 * fails as a defect instead of as `undefined.length`.
 */
type SpecSchema = {
  readonly properties?: Record<string, unknown>;
};

type CommittedSpec = {
  readonly openapi: string;
  readonly paths: Record<string, unknown>;
  readonly schemas: Record<string, SpecSchema>;
};

/** One table as the catalog presents it, and the columns it really has. */
type CatalogTable = {
  readonly schema: string;
  readonly name: string;
  readonly columns: readonly string[];
};

const config = databaseConfig();
let client: Client;
let connected = false;

beforeAll(async () => {
  client = new Client(config);
  await client.connect();
  connected = true;
});

afterAll(async () => {
  if (connected) {
    await client.end();
  }
});

/**
 * The schemas PostgREST serves, read from `postgrest.conf` rather than hardcoded.
 *
 * Two reasons, and the second is the one that matters. Hardcoding `public` would
 * make the gate keep asserting the OLD answer after somebody adds a schema — a
 * baseline that goes stale quietly, which is the defect class this whole file
 * exists to end. Reading the configuration means a `db-schemas` change **turns the
 * gate red on the new tables** instead of leaving it green over a schema nobody
 * looks at.
 *
 * **No default.** An absent `db-schemas` throws rather than assuming PostgREST's own
 * default of `public`: this gate's entire claim is that it is checking the right
 * set, and a silently assumed set would be the one thing it cannot check.
 */
function servedSchemas(): readonly string[] {
  const config_ = readFileSync(CONFIG_PATH, 'utf8');
  const match = /^[ \t]*db-schemas[ \t]*=[ \t]*(.*)$/m.exec(config_);
  const value = match?.[1];
  if (value === undefined) {
    throw new Error(
      `${relativeToRepository(CONFIG_PATH)} does not set db-schemas, so this gate cannot tell which schemas the ` +
        'contract is meant to describe. Add the key rather than letting the gate assume PostgREST\'s default.',
    );
  }

  // `"public"` or `"public", "authz"` — PostgREST's own syntax is a comma-separated
  // list of quoted identifiers.
  const schemas = value
    .split(',')
    .map((entry) => entry.trim().replace(/^"|"$/g, ''))
    .filter((entry) => entry !== '');
  if (schemas.length === 0) {
    throw new Error(`db-schemas is present in ${relativeToRepository(CONFIG_PATH)} but names no schema`);
  }
  return schemas;
}

function readCommittedSpec(): CommittedSpec {
  const parsed: unknown = JSON.parse(readFileSync(SPEC_PATH, 'utf8'));
  if (typeof parsed !== 'object' || parsed === null) {
    throw new Error(`${relativeToRepository(SPEC_PATH)} is not a JSON object`);
  }
  const document = parsed as Record<string, unknown>;

  const openapi = document['openapi'];
  if (typeof openapi !== 'string' || !openapi.startsWith('3.')) {
    // `openapi-typescript` targets OpenAPI 3.x and PostgREST serves 2.0, so the
    // committed file is the CONVERTED one (ADR-0003). A `swagger: "2.0"` here means
    // the conversion step was skipped, which is a different defect with a different
    // fix and is reported as such rather than as a column mismatch.
    throw new Error(
      `${relativeToRepository(SPEC_PATH)} declares ${JSON.stringify(openapi)} rather than an OpenAPI 3.x ` +
        'document. PostgREST serves Swagger 2.0 and the committed contract is the swagger2openapi conversion of it ' +
        '(docs/adr.md ADR-0003); regenerate through that chain.',
    );
  }

  const paths = document['paths'];
  if (typeof paths !== 'object' || paths === null) {
    throw new Error(`${relativeToRepository(SPEC_PATH)} has no paths object`);
  }

  const components = document['components'];
  const schemas =
    typeof components === 'object' && components !== null
      ? (components as Record<string, unknown>)['schemas']
      : undefined;
  if (typeof schemas !== 'object' || schemas === null) {
    throw new Error(`${relativeToRepository(SPEC_PATH)} has no components.schemas object`);
  }

  return { openapi, paths: paths as Record<string, unknown>, schemas: schemas as Record<string, SpecSchema> };
}

/**
 * Every table PostgREST would serve, from `pg_class`.
 *
 * **`relkind IN ('r','p','v','m')` — the relations PostgREST exposes** — rather
 * than `information_schema.tables`, which is the narrower `BASE TABLE` view.
 * `information_schema` omits materialised views entirely (verified: the live
 * `authz` schema holds exactly one relation, the `org_closure` matview, and
 * `information_schema.tables` reports **zero** rows for it). Using it would mean a
 * `db-schemas` regression naming `authz` passed this gate silently, because the one
 * thing that schema would contribute is the one thing the narrower view cannot see.
 *
 * `NOT relispartition`: PostgREST serves the partitioned PARENT, never a child as a
 * resource of its own.
 *
 * **`a.attname::text` is load-bearing.** `pg_attribute.attname` is of type `name`,
 * so a bare `array_agg(a.attname)` aggregates to `name[]` — OID 1003 — which is not
 * one of the array types node-postgres decodes. It arrives as the raw PostgreSQL
 * literal `{id,username,…}`, and iterating that string yields one element per
 * CHARACTER, so every table reports every column as missing and the gate fails while
 * proving nothing. Cast to `text` for OID 1009, which is decoded. (Measured, not
 * assumed: `typeof row.columns === 'string'` and `JSON.stringify` gives `"{" + …
 * + "}"`.)
 */
async function catalogTables(schemas: readonly string[]): Promise<readonly CatalogTable[]> {
  const result = await client.query<{ schema: string; name: string; columns: string[] }>(
    `SELECT n.nspname AS schema,
            c.relname AS name,
            array_agg(a.attname::text ORDER BY a.attname) AS columns
       FROM pg_class c
       JOIN pg_namespace n ON n.oid = c.relnamespace
       JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
      WHERE n.nspname = ANY($1)
        AND c.relkind IN ('r', 'p', 'v', 'm')
        AND NOT c.relispartition
      GROUP BY n.nspname, c.relname
      ORDER BY n.nspname, c.relname`,
    [schemas],
  );
  return result.rows.map((row) => ({ schema: row.schema, name: row.name, columns: row.columns }));
}

/**
 * The table paths in the committed document.
 *
 * `/` is PostgREST's description of the API itself, and `/rpc/**` are functions
 * rather than tables — `openapi-mode = "ignore-privileges"` advertises every function
 * in `db-schemas` too, and PostgREST 16.4 emits exactly two of them here
 * (`has_permission`, `ccpa_applicable`). Treating them as tables would demand a
 * `/rpc/has_permission` component schema that no conversion produces.
 */
function tablePaths(spec: CommittedSpec): readonly string[] {
  return Object.keys(spec.paths)
    .filter((path) => path.startsWith('/') && path !== '/' && !path.startsWith('/rpc/'))
    .map((path) => path.replace(/^\//, ''))
    .sort();
}

describe('the committed OpenAPI contract is not stale', () => {
  it(
    'reads a real document and a real schema, so the comparison below is not vacuous',
    async () => {
      const spec = readCommittedSpec();
      const tables = await catalogTables(servedSchemas());

      // The failure this gate exists to prevent was a document with NO paths at all,
      // so the path count is asserted rather than inferred: an empty `paths` object
      // satisfies every "does the spec contain X" assertion below.
      expect(tablePaths(spec).length).toBeGreaterThan(0);
      expect(Object.keys(spec.schemas).length).toBeGreaterThan(0);

      // And a catalog that came back EMPTY would make the same assertions pass for
      // the wrong reason — a schema name PostgREST serves but this connection cannot
      // see. Both sides of the comparison must be non-empty for either to mean
      // anything.
      expect(tables.length, 'the catalog returned no tables, so nothing below can fail').toBeGreaterThan(0);
    },
    TIMEOUT,
  );

  it(
    'describes every table the served schemas have, with a path and a component schema for each',
    async () => {
      const spec = readCommittedSpec();
      const tables = await catalogTables(servedSchemas());
      const documented = new Set(tablePaths(spec));

      // The named direction: the database has it, the contract does not. This is the
      // half that was invisible for thirteen migrations — nothing failed because
      // nothing asked.
      const missing = tables
        .filter((table) => !documented.has(table.name))
        .map((table) => `${table.schema}.${table.name}`);
      expect(missing, 'the database has these tables and openapi.json does not describe them').toEqual([]);

      // A path without a schema is the conversion losing a definition, which is a
      // DIFFERENT defect from a missing path and is reported as one.
      const withoutSchema = [...documented].filter((name) => spec.schemas[name] === undefined).sort();
      expect(withoutSchema, 'openapi.json has a path for these tables but no component schema').toEqual([]);
    },
    TIMEOUT,
  );

  it(
    'describes every column of every table, and no column the database does not have',
    async () => {
      const spec = readCommittedSpec();
      const tables = await catalogTables(servedSchemas());

      const missing: string[] = [];
      const extra: string[] = [];
      for (const table of tables) {
        const documented = new Set(Object.keys(spec.schemas[table.name]?.properties ?? {}));
        const inDatabase = new Set(table.columns);
        for (const column of inDatabase) {
          if (!documented.has(column)) {
            missing.push(`${table.name}.${column}`);
          }
        }
        for (const column of documented) {
          if (!inDatabase.has(column)) {
            extra.push(`${table.name}.${column}`);
          }
        }
      }

      expect(missing, 'openapi.json omits columns the database has').toEqual([]);
      // The reverse direction, because a renamed or dropped column leaves the other
      // half of the staleness: the contract advertises a field no request can return,
      // and the generated Angular types carry a property that does not exist.
      expect(extra, 'openapi.json describes columns the database does not have').toEqual([]);
    },
    TIMEOUT,
  );

  it(
    'describes no table the served schemas do not have, so a dropped table is caught too',
    async () => {
      const spec = readCommittedSpec();
      const tables = await catalogTables(servedSchemas());
      const inDatabase = new Set(tables.map((table) => table.name));

      expect(tablePaths(spec).filter((name) => !inDatabase.has(name)), 'openapi.json describes tables that no longer exist').toEqual(
        [],
      );
    },
    TIMEOUT,
  );

  it(
    'carries no view and no materialised view in a served schema, so the table set above is the whole surface',
    async () => {
      // §B2 / ADR-0022: no views, because a superuser-created view bypasses every RLS
      // policy on its base table silently and writes through one are unreliable. The
      // comparison above reads `relkind` across `r`, `p`, `v` and `m` so a `db-schemas`
      // regression is visible; THIS is what says a `v` or `m` there is a defect rather
      // than a legitimately served relation, rather than leaving it to a reader to
      // work out from the relkind list.
      const result = await client.query<{ schema: string; name: string; kind: string }>(
        `SELECT n.nspname AS schema, c.relname AS name, c.relkind::text AS kind
           FROM pg_class c
           JOIN pg_namespace n ON n.oid = c.relnamespace
          WHERE n.nspname = ANY($1) AND c.relkind IN ('v', 'm') AND NOT c.relispartition
          ORDER BY 1, 2`,
        [servedSchemas()],
      );
      expect(result.rows.map((row) => `${row.schema}.${row.name} (${row.kind})`), 'AGENTS.md B2 allows no views').toEqual([]);
    },
    TIMEOUT,
  );
});

describe('authz is outside the served surface, so none of it is advertised', () => {
  it(
    'is not named by db-schemas, which is the configuration half of the invariant',
    () => {
      // The other half is the table comparison above: `authz` holds exactly one
      // relation, the `org_closure` MATVIEW, so this assertion is the only thing that
      // reports the regression by name. Both are kept, because either alone passes:
      // `db-schemas` could name `authz` and the table set could be widened without
      // this, and the table set is derived from the same key this reads.
      expect(servedSchemas()).not.toContain('authz');
    },
    TIMEOUT,
  );

  it(
    'contributes no path and no component schema to the committed document',
    () => {
      const spec = readCommittedSpec();

      // NAMES, not substrings. `authz` DOES occur in the committed document — twice,
      // inside the `users.last_activity_at` description, which names the retention
      // scan that maintains the column. A substring scan would be permanently red for
      // a correct spec, which is exactly how a gate earns a skip.
      const authzPaths = Object.keys(spec.paths).filter((path) => path.toLowerCase().includes('authz'));
      expect(authzPaths, 'openapi.json advertises an authz path').toEqual([]);

      const authzSchemas = Object.keys(spec.schemas).filter((name) => name.toLowerCase().includes('authz'));
      expect(authzSchemas, 'openapi.json carries an authz component schema').toEqual([]);
    },
    TIMEOUT,
  );
});